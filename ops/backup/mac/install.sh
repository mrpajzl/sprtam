#!/bin/sh
# A third copy of the backups on the admin's Mac (docs/OBSAH.md, Zálohy): out of reach of Coolify and both
# servers. A LaunchAgent runs ops/backup/backup.py every hour while the Mac is awake and signed in; without
# the git mirror. Needs `age` (brew install age), the backup token in ~/.config/sprtam/backup-token and the
# age identity in ~/.config/sprtam/backup-age-identity.txt (its public key is the recipient).
#   sh ops/backup/mac/install.sh            install or update
#   sh ops/backup/mac/install.sh remove     uninstall (the copies stay in ~/.local/state/sprtam-backup)
set -eu
LABEL=cz.sprtam.backup
APP="$HOME/.local/share/sprtam-backup"
STATE="$HOME/.local/state/sprtam-backup"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"

if [ "${1:-}" = remove ]; then
  launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
  rm -f "$PLIST"
  echo "Removed $LABEL (copies kept in $STATE)."
  exit 0
fi

command -v age >/dev/null || { echo 'age is missing: brew install age'; exit 1; }
[ -s "$HOME/.config/sprtam/backup-token" ] || { echo 'missing ~/.config/sprtam/backup-token'; exit 1; }
[ -s "$HOME/.config/sprtam/backup-age-identity.txt" ] || { echo 'missing ~/.config/sprtam/backup-age-identity.txt'; exit 1; }
umask 077
mkdir -p "$APP" "$STATE"
cp "$(dirname "$0")/../backup.py" "$APP/backup.py"
cat > "$APP/run.sh" <<RUN
#!/bin/sh
# Generated by ops/backup/mac/install.sh. Secrets are read from files at run time, never stored here.
export PATH="/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin"
export BACKUP_TOKEN="\$(cat "$HOME/.config/sprtam/backup-token")"
export AGE_RECIPIENTS="\$(age-keygen -y "$HOME/.config/sprtam/backup-age-identity.txt")"
export DATA_DIR="$STATE" BACKUP_SOURCE=mac SPRTAM_API=https://moderace.sprtam.cz
exec python3 "$APP/backup.py" once
RUN
chmod 700 "$APP/run.sh"
cat > "$PLIST" <<PL
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key><array><string>/bin/sh</string><string>$APP/run.sh</string></array>
  <key>StartInterval</key><integer>3600</integer>
  <key>RunAtLoad</key><true/>
  <key>StandardOutPath</key><string>$STATE/log.txt</string>
  <key>StandardErrorPath</key><string>$STATE/log.txt</string>
</dict></plist>
PL
launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"
echo "Installed $LABEL: hourly copies in $STATE (log: $STATE/log.txt)."
